                    white-space:nowrap; border:1px solid currentColor; }
            .verified { color:var(--good); } .served, .info { color:var(--accent); }
            .notverified, .warn { color:var(--warn); } .error { color:var(--bad); } .planned { color:var(--muted); }
            .none { color:var(--muted); font-style:italic; }
