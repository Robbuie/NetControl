using System.Globalization;
using System.Net;
using System.Text;
using NetControl.Core.Persistence;

namespace NetControl.Core.Reporting;

/// <summary>
/// The commissioning record as one self-contained HTML page - the startup record a customer is handed
/// at the end of a job. It prints to PDF from any browser, and it needs nothing but the file it is in.
///
/// <para><b>It reads the project file and nothing else.</b> No live state, no adapter, no clock but
/// the one stamping when it was generated - so a report regenerated from the same project file on a
/// different laptop next year says exactly the same thing. Every time in it is UTC for the same
/// reason: a record that changes with the time zone of whoever opens it is not one record.</para>
///
/// <para>Every device's state is the record's: Verified only where the last finished operation was a
/// readback that matched (see <see cref="CommissioningRecord"/>), served only where an
/// <c>Assignment</c> row says so. Nothing in the report is inferred that the record does not say.</para>
///
/// <para>All text from the file is HTML-encoded on the way out. A project file is a SQLite database
/// somebody may have edited by hand, and a note containing markup must come out as the text it is.</para>
/// </summary>
public static class CommissioningReport
{
    private const string TimeFormat = "yyyy-MM-dd HH:mm:ss 'UTC'";

    /// <summary>Builds the page.</summary>
    /// <param name="project">The project to report on. Read only.</param>
    /// <param name="generatedUtc">When, for the header.</param>
    /// <param name="generatedBy">The build generating it - "NetControl 0.8.0+abc1234" - for the header.</param>
    public static string BuildHtml(ProjectStore project, DateTimeOffset generatedUtc, string? generatedBy = null)
    {
        ArgumentNullException.ThrowIfNull(project);

        IReadOnlyList<DeviceRecord> devices = project.Devices.All();
        IReadOnlyList<EventRecord> events = project.Events.All();
        IReadOnlyList<ScanRunRecord> scans = project.Scans.Runs();
        IReadOnlyDictionary<long, DeviceCommissioning> outcomes = CommissioningRecord.LastOutcomes(events);
        Dictionary<long, AssignmentRecord> lastServed = LastServed(project, devices);

        var html = new StringBuilder(64 * 1024);

        Head(html, project);

        html.Append("<header>");
        html.Append(CultureInfo.InvariantCulture, $"<h1>{E(project.Project.Name)}</h1>");
        html.Append("<p class=\"sub\">Commissioning record</p>");
        html.Append("<dl class=\"meta\">");
        Meta(html, "Project file", project.IsInMemory ? "not saved to a file" : project.FilePath);
        Meta(html, "Project created", Time(project.Project.CreatedUtc));
        Meta(html, "Report generated", Time(generatedUtc));
        Meta(html, "Generated by", generatedBy ?? "NetControl");
        Meta(html, "Builds that wrote to it", BuildsIn(events));
        html.Append("</dl></header>");

        Summary(html, devices, outcomes, lastServed, events);
        DeviceTable(html, devices, outcomes, lastServed);
        Attention(html, events, devices);
        Commissioning(html, events, devices);
        ScanTable(html, scans);
        EventLog(html, events, devices);

        html.Append("<footer>Generated from the project file's append-only event log. Every row in it was written ");
        html.Append("as the operation happened, and the file refuses any change to it.</footer>");
        html.Append("</body></html>");

        return html.ToString();
    }

    private static void Head(StringBuilder html, ProjectStore project)
    {
        html.Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">");
        html.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        html.Append(CultureInfo.InvariantCulture, $"<title>{E(project.Project.Name)} - commissioning record</title>");
        html.Append("<style>");
        html.Append("""
            :root { --ink:#1d2329; --muted:#5d6670; --line:#d5dade; --soft:#f3f5f7; --good:#1f7a43;
                    --warn:#9a6200; --bad:#b3261e; --accent:#2b5da8; }
            * { box-sizing:border-box; }
            body { font:14px/1.45 "Segoe UI", system-ui, -apple-system, sans-serif; color:var(--ink);
                   margin:0 auto; max-width:1180px; padding:28px 24px 40px; background:#fff; }
            h1 { font-size:26px; margin:0; } h2 { font-size:17px; margin:30px 0 8px; padding-bottom:4px;
                   border-bottom:2px solid var(--ink); }
            .sub { margin:2px 0 14px; color:var(--muted); text-transform:uppercase; letter-spacing:.08em;
                   font-size:12px; font-weight:600; }
            dl.meta { display:grid; grid-template-columns:max-content 1fr; gap:3px 18px; margin:0; font-size:13px; }
            dl.meta dt { color:var(--muted); } dl.meta dd { margin:0; word-break:break-all; }
            .tiles { display:grid; grid-template-columns:repeat(auto-fit,minmax(150px,1fr)); gap:10px; margin-top:22px; }
            .tile { border:1px solid var(--line); border-radius:6px; padding:10px 12px; }
            .tile b { display:block; font-size:24px; } .tile span { color:var(--muted); font-size:12px; }
            table { border-collapse:collapse; width:100%; font-size:12.5px; }
            th, td { text-align:left; vertical-align:top; padding:5px 7px; border-bottom:1px solid var(--line); }
            th { background:var(--soft); font-weight:600; white-space:nowrap; }
            tr { break-inside:avoid; }
            .mono { font-family:Consolas, "Cascadia Mono", monospace; white-space:nowrap; }
            .muted { color:var(--muted); }
