        html.Append("</style></head><body>");
    }

    private static void Summary(
        StringBuilder html,
        IReadOnlyList<DeviceRecord> devices,
        IReadOnlyDictionary<long, DeviceCommissioning> outcomes,
        Dictionary<long, AssignmentRecord> lastServed,
        IReadOnlyList<EventRecord> events)
    {
        int verified = devices.Count(d => State(d, outcomes, lastServed) == "Verified");
        int notVerified = devices.Count(d => State(d, outcomes, lastServed) == "Not verified");
        int served = lastServed.Count;
        int addressed = devices.Count(d => d.PlannedIp is not null);
        int warnings = events.Count(e => e.Severity == EventSeverity.Warn);
        int errors = events.Count(e => e.Severity == EventSeverity.Error);

        html.Append("<div class=\"tiles\">");
        Tile(html, devices.Count, "devices in the plan");
        Tile(html, addressed, "with a planned address");
        Tile(html, served, "served an address");
        Tile(html, verified, "verified static", verified == addressed && addressed > 0 ? "verified" : null);
        Tile(html, notVerified, "last attempt not verified", notVerified > 0 ? "notverified" : null);
        Tile(html, warnings + errors, "warnings and errors in the log", errors > 0 ? "error" : warnings > 0 ? "warn" : null);
        html.Append("</div>");
    }

    private static void DeviceTable(
        StringBuilder html,
        IReadOnlyList<DeviceRecord> devices,
        IReadOnlyDictionary<long, DeviceCommissioning> outcomes,
        Dictionary<long, AssignmentRecord> lastServed)
    {
        html.Append("<h2>Devices</h2>");

        if (devices.Count == 0)
        {
            html.Append("<p class=\"none\">The plan is empty.</p>");
            return;
        }

        html.Append("<table><thead><tr><th>MAC</th><th>Device</th><th>Panel</th><th>Planned address</th>");
        html.Append("<th>Vendor</th><th>State</th><th>Served</th><th>Last write</th><th>Notes</th></tr></thead><tbody>");

        foreach (DeviceRecord device in devices.OrderBy(d => Numeric(d.PlannedIp)).ThenBy(d => d.Mac.ToString()))
        {
            string state = State(device, outcomes, lastServed);
            outcomes.TryGetValue(device.Id, out DeviceCommissioning? last);
            lastServed.TryGetValue(device.Id, out AssignmentRecord? served);

            string address = device.PlannedIp is null
                ? "<span class=\"none\">none</span>"
                : $"<span class=\"mono\">{E(device.PlannedIp)}</span>"
                    + (device.PlannedMask is null ? string.Empty : $"<br><span class=\"mono muted\">mask {E(device.PlannedMask)}</span>")
                    + (device.PlannedGateway is null ? string.Empty : $"<br><span class=\"mono muted\">gw {E(device.PlannedGateway)}</span>");

            string stateClass = state.Replace(" ", string.Empty, StringComparison.Ordinal).ToLowerInvariant();

            string servedCell = served is null
                ? "<span class=\"none\">no</span>"
                : $"<span class=\"mono\">{E(served.ServedIp)}</span><br>"
                    + $"<span class=\"muted\">{E(Time(served.ServedUtc))} on {E(served.NicName)}</span>";

            string lastCell = last is null
                ? "<span class=\"none\">nothing written</span>"
                : $"{E(last.Message)}<br><span class=\"muted\">{E(Time(last.Utc))}</span>";

            html.Append("<tr>");
            html.Append(CultureInfo.InvariantCulture, $"<td class=\"mono\">{E(device.Mac)}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{E(device.DisplayName)}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{E(device.PanelRef)}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{address}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{E(device.Vendor)}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td><span class=\"pill {stateClass}\">{E(state)}</span></td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{servedCell}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{lastCell}</td>");
            html.Append(CultureInfo.InvariantCulture, $"<td>{E(device.Notes)}</td>");
            html.Append("</tr>");
        }

        html.Append("</tbody></table>");
    }

    private static void Attention(StringBuilder html, IReadOnlyList<EventRecord> events, IReadOnlyList<DeviceRecord> devices)
    {
        List<EventRecord> flagged = [.. events.Where(e => e.Severity != EventSeverity.Info)];

        html.Append("<h2>Needs attention</h2>");

        if (flagged.Count == 0)
        {
            html.Append("<p class=\"none\">Nothing in the record was graded a warning or an error.</p>");
            return;
        }

        html.Append("<p class=\"muted\">Every warning and error in the record, oldest first.</p>");
        EventRows(html, flagged, devices);
    }

    private static void Commissioning(StringBuilder html, IReadOnlyList<EventRecord> events, IReadOnlyList<DeviceRecord> devices)
    {
        List<EventRecord> cip = [.. events.Where(e => e.Category == EventCategory.Cip)];

        html.Append("<h2>Writes to devices</h2>");

        if (cip.Count == 0)
        {
            html.Append("<p class=\"none\">Nothing was written to any device over EtherNet/IP.</p>");
            return;
        }

        html.Append("<p class=\"muted\">Every EtherNet/IP step - Set static, hand-backs, diagnostics reads - as it ");
        html.Append("happened, including what was sent and what came back.</p>");
        EventRows(html, cip, devices);
    }

    private static void ScanTable(StringBuilder html, IReadOnlyList<ScanRunRecord> scans)
    {
        html.Append("<h2>Scans</h2>");

        if (scans.Count == 0)
        {
            html.Append("<p class=\"none\">No scan was run in this project.</p>");
            return;
        }

        html.Append("<table><thead><tr><th>When</th><th>Adapter</th><th>Subnet</th><th>Devices answered</th>");
        html.Append("</tr></thead><tbody>");

        foreach (ScanRunRecord scan in scans.OrderBy(s => s.Utc).ThenBy(s => s.Id))
        {
            string subnet = scan.TryGetSubnet(out Ipv4Subnet s) ? s.ToString() : string.Empty;

            html.Append(CultureInfo.InvariantCulture,
                $"<tr><td class=\"mono\">{E(Time(scan.Utc))}</td><td>{E(scan.NicName)}</td>"
                + $"<td class=\"mono\">{E(subnet)}</td><td>{scan.Answered}</td></tr>");
        }

        html.Append("</tbody></table>");
    }

    private static void EventLog(StringBuilder html, IReadOnlyList<EventRecord> events, IReadOnlyList<DeviceRecord> devices)
    {
        html.Append("<h2>Event log</h2>");

        if (events.Count == 0)
        {
            html.Append("<p class=\"none\">The record is empty.</p>");
            return;
        }

        html.Append(CultureInfo.InvariantCulture,
            $"<p class=\"muted\">All {events.Count} row(s), oldest first, exactly as recorded.</p>");
        EventRows(html, events, devices);
    }

    private static void EventRows(StringBuilder html, IEnumerable<EventRecord> rows, IReadOnlyList<DeviceRecord> devices)
    {
        Dictionary<long, DeviceRecord> byId = devices.ToDictionary(d => d.Id);

        html.Append("<table><thead><tr><th>When</th><th></th><th>Category</th><th>About</th><th>What happened</th>");
        html.Append("</tr></thead><tbody>");

        foreach (EventRecord row in rows.OrderBy(e => e.Id))
        {
            string about = row.DeviceId is { } id && byId.TryGetValue(id, out DeviceRecord? device)
                ? (device.DisplayName ?? device.Mac.ToString())
                : row.Target ?? string.Empty;

            string severity = row.Severity switch
            {
                EventSeverity.Error => "error",
                EventSeverity.Warn => "warn",
                _ => "info",
            };

            html.Append(CultureInfo.InvariantCulture,
                $"<tr><td class=\"mono\">{E(Time(row.Utc))}</td>"
                + $"<td><span class=\"pill {severity}\">{severity}</span></td>"
                + $"<td>{E(SqlCategory(row.Category))}</td><td>{E(about)}</td><td>{E(row.Message)}</td></tr>");
        }

        html.Append("</tbody></table>");
    }

    /// <summary>The state the record supports, in the words the grid uses.</summary>
    private static string State(
        DeviceRecord device,
        IReadOnlyDictionary<long, DeviceCommissioning> outcomes,
        Dictionary<long, AssignmentRecord> lastServed)
    {
        if (outcomes.TryGetValue(device.Id, out DeviceCommissioning? last))
        {
            switch (last.Outcome)
            {
                case CommissioningOutcome.Verified
                    when device.PlannedIp is { } planned
                        && (last.Readback is null || last.Readback.StartsWith($"ip={planned} ", StringComparison.Ordinal)):
                    return "Verified";

                case CommissioningOutcome.NotVerified:
                    return "Not verified";

                case CommissioningOutcome.HandedBack:
                    return "Handed back";
            }
        }

        return lastServed.ContainsKey(device.Id) ? "Served" : "Planned";
    }

    private static Dictionary<long, AssignmentRecord> LastServed(ProjectStore project, IReadOnlyList<DeviceRecord> devices)
    {
        var served = new Dictionary<long, AssignmentRecord>();

        foreach (DeviceRecord device in devices)
        {
            // Newest first, so the first is the latest.
            if (project.Assignments.ForDevice(device.Id) is [var latest, ..])
            {
                served[device.Id] = latest;
            }
        }

        return served;
    }

    /// <summary>The distinct builds that stamped the file - "Opened by NetControl 0.8.0." rows.</summary>
    private static string BuildsIn(IReadOnlyList<EventRecord> events)
    {
        string[] builds = [.. events
            .Where(e => e.Category == EventCategory.App
                && e.Message.StartsWith("Opened by ", StringComparison.Ordinal))
            .Select(e => e.Message["Opened by ".Length..].TrimEnd('.'))
            .Distinct(StringComparer.Ordinal)];

        return builds.Length == 0 ? "not recorded" : string.Join(", ", builds);
    }

    private static void Meta(StringBuilder html, string term, string value) =>
        html.Append(CultureInfo.InvariantCulture, $"<dt>{E(term)}</dt><dd>{E(value)}</dd>");

    private static void Tile(StringBuilder html, int value, string label, string? tone = null) =>
        html.Append(CultureInfo.InvariantCulture,
            $"<div class=\"tile\"><b class=\"{tone ?? string.Empty}\">{value}</b><span>{E(label)}</span></div>");

    private static string Time(DateTimeOffset value) =>
        value.ToUniversalTime().ToString(TimeFormat, CultureInfo.InvariantCulture);

    private static string SqlCategory(EventCategory category) => category.ToString().ToLowerInvariant();

    private static string E(object? value) => WebUtility.HtmlEncode(value?.ToString() ?? string.Empty);

    private static uint Numeric(IPAddress? address)
    {
        if (address is null)
        {
            return uint.MaxValue;
        }

        byte[] bytes = address.GetAddressBytes();
        return bytes.Length == 4
            ? ((uint)bytes[0] << 24) | ((uint)bytes[1] << 16) | ((uint)bytes[2] << 8) | bytes[3]
            : uint.MaxValue;
    }
}
